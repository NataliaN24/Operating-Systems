Напишете серия от команди, извеждащи на екрана
само inode-а на най-скоро променения (по съдържание)
файл, намиращ се в home директорията на потребител pesho
(или нейните поддиректории), който има повече от едно име.

find /home/pesho -type f -links +1  -printf '%T@ %i\n' | sort -nr |head -n 1 | cut -f 2 -d ' '



В find -printf:

%T → време на последна модификация на съдържанието

@ → в epoch формат (секунди)
