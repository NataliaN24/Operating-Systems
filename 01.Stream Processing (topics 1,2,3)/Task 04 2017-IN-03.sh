

awk -F: '$5 ~ /Inf/ {
  split($5,a,","); n=split(a[1],b," ");
  if (b[n] ~ /a$/) print substr($1,3,2)
}' /etc/passwd | sort | uniq -c | sort -nr | head -1


Условието $5 ~ /Inf/ означава, че се обработват само редовете, в които 5-тото поле съдържа текста „Inf“. Операторът ~ проверява съвпадение с регулярен израз.

split($5,a,",") разделя comment полето по запетая, като в a[1] остава „Име Фамилия“. След това n=split(a[1],b," ") разделя това по интервал и b[n] е последната дума (фамилията). Условието b[n] ~ /a$/ проверява дали фамилията завършва на „a“ ($ означава край на низа).

substr($1,3,2) извлича подниз от username-а – започва от позиция 3 и взима 2 символа, което са 2-рата и 3-тата цифра от факултетния номер.
