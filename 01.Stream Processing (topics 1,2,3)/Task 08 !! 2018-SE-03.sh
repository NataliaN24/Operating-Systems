Обяснение на целия синтаксис (по части)
1) gid_si=$( ... )

gid_si= създава променлива в shell.

$( ... ) е command substitution: изпълнява командите вътре и слага резултата като стойност.

2) sort -t: -k3,3n /etc/passwd

sort подрежда редовете.

-t: казва: разделителят между “колоните” е :.

-k3,3n сортира по 3-тото поле (UID) числово:

k3,3 → само по поле 3

n → numeric (числово)

/etc/passwd е входният файл (структурата му е с : полета). 

etc

3) | sed -n '201p'

| (pipe) подава изхода на sort към sed.

sed -n казва “не печатай по подразбиране”.

'201p' означава: отпечатай 201-вия ред (p = print).

Така взимаме “201-вия акаунт при подреждане по UID”.

4) | cut -d: -f4

cut реже по разделител.

-d: → разделител е :

-f4 → взима 4-то поле (GID)

Така получаваме gid_si = GID на “СИ” групата според условието.

5) awk -F: -v gid="$gid_si" ' ... ' /etc/passwd

awk обработва файла ред по ред и по полета.

-F: разделя полетата по : (като при passwd).

-v gid="$gid_si" подава shell променливата gid_si вътре в awk като awk-променлива gid.

' ... ' е програмата на awk.

/etc/passwd е файлът, който awk чете.

Вътре в awk програмата
6) Условие:
$4==gid && $1 ~ /^s[0-9]+$/


$4 е 4-то поле (GID).

== сравнение.

&& логическо AND.

$1 е 1-во поле (username).

~ match-ва регулярен израз.

/^s[0-9]+$/ значи:

^ начало на низа

s буквално “s”

[0-9]+ една или повече цифри

$ край на низа
→ т.е. username като s61756, s61807 и т.н.

Така остават само “студентските” акаунти от СИ групата.

7) Тяло (какво правим с тези редове):
name=$5; sub(/,.*/, "", name)


name=$5 → взима 5-то поле (comment).

sub(/,.*/, "", name):

sub(regex, replacement, var) прави замяна 1 път.

/,.* / означава “запетая и всичко след нея”.

"" означава “замени с празно”.
→ остава само “Име Фамилия” (без “, SI, ...”).

fn=substr($1,2)


substr(string, start):

взима подниз от string, започвайки от позиция start.

substr($1,2) маха първия символ s → остава само фак. номер като низ (например 61756).

print fn "\t" name ":" $6


print отпечатва.

"\t" е таб (използваме го, за да сортираме лесно по първата “колона”).

$6 е home директорията.

Т.е. печатаме ред като:

61756<TAB>Katrin Kartuleva:/home/SI/s61756

8) | sort -n -k1,1

сортира по първата “колона” (фак. номер), числово.

-k1,1 означава: само по поле 1.

9) | cut -f2-

cut -f работи по таб-разделени полета (тук имаме \t).

-f2- означава: вземи от поле 2 до края.

Така махаме помощния фак. номер отпред и остава само:

Име Фамилия:/home/...
