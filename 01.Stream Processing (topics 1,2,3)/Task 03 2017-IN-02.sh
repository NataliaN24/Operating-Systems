 Напишете серия от команди, които изтриват:
а) всички файлове в текущата директория и нейните 
поддиректории, които са с нулева дължина.

find . -type f -size 0c -delete

#or
find . -type f -size 0 -exec rm {} \;

б) 5-е най-големи файла в home директорията на
текущия потребител и нейните поддиректории

find "$HOME" -type f -printf '%s %p\n' | sort -nr |head -n 5
